"""PC-only helper; never connects to hardware and never rewrites XY geometry."""

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from monitor.jobs import parse_program
from monitor.profiles import check_cam_program, fingerprint, fit_profile


def main():
    """Print CAM values or label a file explicitly regenerated by its operator."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", type=Path)
    parser.add_argument("--depth", type=float)
    parser.add_argument("--tag", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--confirm-cam-profile", action="store_true",
                        help="Confirm CAM already used this profile's tool.")
    args = parser.parse_args()
    try:
        exported = json.loads(args.profile.read_text(encoding="utf-8"))
        profile = exported["profile"]
        if exported["version"] != 1 or profile["fingerprint"] != (
            fingerprint(profile)
        ):
            raise ValueError("Invalid profile fingerprint/version")
        fitted = fit_profile(profile["observations"])
        if any(profile[key] != fitted[key] for key in ("conditions", "model")):
            raise ValueError("Profile measurements do not match model")
        model = profile["model"]
        if args.tag:
            if not args.output or not args.confirm_cam_profile:
                raise ValueError("Tagging requires --output and "
                                 "--confirm-cam-profile")
            if args.output.exists():
                raise ValueError("Output already exists; choose a new file")
            content = args.tag.read_text(encoding="ascii")
            marker = (f"; BARK_BEETLE_PROFILE {profile['id']} "
                      f"{profile['fingerprint']}\n")
            program = parse_program(args.output.name, marker + content)
            check_cam_program(profile, program, {})
            # Exclusive creation protects an existing program on races too.
            with args.output.open("x", encoding="ascii", newline="\n") as out:
                out.write(marker + content)
            print(str(args.output.resolve()))
        else:
            depth = profile.get("depth", args.depth)
            if args.depth is not None and "depth" in profile and abs(
                args.depth - depth
            ) > 1e-9:
                raise ValueError("Depth is fixed by the selected profile")
            if depth is None or not model["min_depth"] <= depth <= (
                model["max_depth"]
            ):
                raise ValueError("--depth must be inside measured range")
            diameter = model["intercept_mm"] + model["slope"] * depth
            if diameter <= 0:
                raise ValueError("Profile predicts a nonpositive tool diameter")
            print(json.dumps({
                "profile_id": profile["id"],
                "tool_diameter_mm": diameter,
                "cut_z_mm": -depth, **profile["conditions"],
            }, indent=2))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()

